#include <stdio.h>

int main()
{
	int a = 20;
	int *b;
	b = &a;
	*b = *b +20;
	
	printf("%d, %d", a, *b);

}

/*
결과값 40, 40


int a = 50;: 정수형 변수 a를 선언하고 50을 저장합니다.
int *b;: 정수형 포인터 변수 b(주소를 저장하는 변수)를 선언합니다.
b = &a;: a의 메모리 주소값(예: 0x1000)을 포인터 b에 저장합니다. 이제 b는 a를 가리킵니다.
*b = *b + 20;:
*b는 포인터 b가 가리키는 주소의 값(즉, a의 값)을 의미하는 간접 참조(Dereference) 연산입니다.
*b는 현재 50입니다.
50 + 20 계산 결과인 70을 *b가 가리키는 위치, 즉 a의 메모리 공간에 직접 저장합니다.
printf("%d, %d", a, *b);: a의 값이 70으로 변경되었으므로 70, 70이 출력됩니다. 
*/
